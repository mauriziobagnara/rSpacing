test_that("CLI names keep their double hyphens", {
  skip_if_not_installed("jsonlite")
  td <- tempfile(); dir.create(td)
  dir.create(file.path(td,"apsim","src","Spacing.Tool2"), recursive=TRUE)
  cfg <- file.path(td,"apsim","spacing.config.json")
  jsonlite::write_json(list(OutputDir=file.path(td,"out"), TempWeatherDir=file.path(td,"weather")), cfg, auto_unbox=TRUE)
  x <- spacing_config(td)
  q <- new_spacing_request(45.4,9.2,"Maize",mock=TRUE)
  args <- build_spacing_args(x,q)
  expect_equal(args[1], "--config")
  expect_true("--lat" %in% args)
  expect_true("--mock" %in% args)
  expect_false("config" %in% args)
})
