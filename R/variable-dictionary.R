#' Describe output variables
#'
#' Shortcut for [spacing_variable_dictionary()] restricted to some variables.
#'
#' @param variable Character vector of aliases (column names).
#' @param source Character vector. `"daily"` and/or `"report"`.
#' @param result Optional `spacing_result` used for units and availability.
#' @return The matching rows of the variable dictionary (same columns).
#' @family results
#' @export
#' @examples
#' describe_spacing_variable("Rain_mm", source = "daily")[, c("title", "unit", "description")]
describe_spacing_variable <- function(variable, source = c("daily", "report"), result = NULL) {
  source <- match.arg(source, several.ok = TRUE)
  spacing_variable_dictionary(result = result, source = source, variables = variable, include_unknown = TRUE)
}

#' Plot labels for a variable
#' @param result A `spacing_result` or `NULL`.
#' @param variable Variable alias.
#' @param source `"daily"` or `"report"`.
#' @return `list(title, subtitle, y, summary)`.
#' @noRd
.spacing_variable_labels <- function(result, variable, source) {
  d <- describe_spacing_variable(variable, source = source, result = result)
  d <- d[d$variable == variable & (is.na(d$source) | d$source == source), , drop = FALSE]
  if (!nrow(d)) return(list(title = variable, subtitle = NULL, y = variable, summary = "mean"))
  z <- d[1L, , drop = FALSE]
  title <- z$title
  description <- z$description
  layer_match <- regexec("^(.+)\\(([0-9]+)\\)$", variable)
  layer_parts <- regmatches(variable, layer_match)[[1L]]
  if (source == "daily" && length(layer_parts) == 3L) {
    daily <- spacing_daily(result, strict = FALSE, allow_empty = TRUE)
    indexed <- if (is.data.frame(daily)) grep("\\([0-9]+\\)$", names(daily), value = TRUE) else character()
    base <- layer_parts[[2L]]
    family <- indexed[sub("\\([0-9]+\\)$", "", indexed) == base]
    if (length(family)) {
      geometry <- tryCatch(spacing_soil_layers(result, n_layers = length(family)), error = function(e) NULL)
      layer_id <- as.integer(layer_parts[[3L]])
      if (!is.null(geometry) && layer_id <= nrow(geometry)) {
        depth_label <- geometry$depth_label[[layer_id]]
        # Remove any static depth contained in the dictionary, then insert only
        # the depth resolved from the APSIMX file. This prevents titles and
        # subtitles from showing both the obsolete and the effective interval.
        title_base <- gsub(
          "\\s+[0-9]+[\u2013-][0-9]+\\s*mm\\s*$",
          "",
          z$title,
          perl = TRUE
        )
        description_base <- gsub(
          "[0-9]+[\u2013-][0-9]+\\s*mm",
          depth_label,
          z$description,
          perl = TRUE
        )
        title <- paste0(title_base, " (", depth_label, ")")
        description <- description_base
      }
    }
  }
  y <- if (!is.na(z$unit) && nzchar(z$unit)) paste0(title, " (", z$unit, ")") else title
  subtitle <- paste(description, paste0("Event: ", z$event), paste0("Recommended annual summary: ", z$recommended_summary), sep = " | ")
  list(title = title, description = description, event = z$event, subtitle = subtitle, y = y, summary = z$recommended_summary)
}

#' Summarise a spacing result
#'
#' Collects run metadata, the table inventory, the catalogue of available
#' variables and the number of variables by scientific group, to show where to
#' look for each kind of output.
#'
#' @param object A `spacing_result`.
#' @param ... Ignored.
#' @return An object of class `summary.spacing_result`: a list with `run`
#'   (the `spacing_run`), `weather` (path of the weather file), `inventory`
#'   ([inventory_spacing_result()]), `variables`
#'   ([spacing_variable_dictionary()] of the result) and `groups` (data frame
#'   with `source`, `group` and `Freq`).
#' @family results
#' @export
#' @examples
#' result <- readRDS(system.file("extdata", "reference_maize", "result.rds",
#'   package = "rSpacing"))
#' s <- summary(result)
#' s
#' head(s$variables[, c("source", "variable", "unit")])
summary.spacing_result <- function(object, ...) {
  .validate_spacing_result(object)
  catalogue <- spacing_variable_dictionary(object, source = c("daily", "report"), include_unknown = TRUE)
  inventory <- inventory_spacing_result(object)
  group_counts <- if (nrow(catalogue)) as.data.frame(table(source = catalogue$source, group = catalogue$group), stringsAsFactors = FALSE) else data.frame()
  group_counts <- group_counts[group_counts$Freq > 0L, , drop = FALSE]
  structure(list(run = object$run, weather = object$weather, inventory = inventory, variables = catalogue, groups = group_counts), class = "summary.spacing_result")
}

#' @describeIn summary.spacing_result Print the summary.
#' @param x A `summary.spacing_result` object.
#' @export
print.summary.spacing_result <- function(x, ...) {
  cat("rSpacing result summary\n")
  cat("=======================\n")
  if (!is.null(x$run$status)) cat("Run status: ", x$run$status, "\n", sep = "")
  if (length(x$weather)) cat("Weather: ", paste(x$weather, collapse = ", "), "\n", sep = "")
  cat("Tables: ", nrow(x$inventory), "\n", sep = "")
  cat("Documented variables available: ", nrow(x$variables), "\n\n", sep = "")
  if (nrow(x$groups)) {
    cat("Where to look by scientific group:\n")
    for (i in seq_len(nrow(x$groups))) cat(sprintf("  - %-16s | %-6s | %d variable(s)\n", x$groups$group[[i]], x$groups$source[[i]], x$groups$Freq[[i]]))
  }
  cat("\nUse summary(result)$variables for the complete catalogue.\n")
  cat("Use describe_spacing_variable('VariableName', source='daily', result=result) for details.\n")
  invisible(x)
}
